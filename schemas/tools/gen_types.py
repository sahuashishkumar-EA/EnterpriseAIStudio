"""Generate TypeScript interfaces and Python TypedDicts from the C01 JSON Schemas (C09-F3).

    python schemas/tools/gen_types.py          # writes sdk/ts/src/generated.ts and
                                               # sdk/python/eap_agent_config/generated.py
    python schemas/tools/gen_types.py --check  # CI: fail if the generated files are stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = ROOT / "schemas" / "v1"
TS_OUT = ROOT / "sdk" / "ts" / "src" / "generated.ts"
PY_OUT = ROOT / "sdk" / "python" / "eap_agent_config" / "generated.py"
HEADER = "Generated by schemas/tools/gen_types.py from schemas/v1. Do not edit."


def pascal(name: str) -> str:
    return "".join(p.capitalize() for p in name.replace("-", "_").split("_"))


def ts_type(s: dict, indent: int = 0) -> str:
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(e) for e in s["enum"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        inner = ts_type(s.get("items", {}), indent)
        return f"Array<{inner}>"
    if t == "object" or "properties" in s:
        props = s.get("properties")
        addl = s.get("additionalProperties")
        if not props:
            if isinstance(addl, dict):
                return f"Record<string, {ts_type(addl, indent)}>"
            return "Record<string, unknown>"
        req = set(s.get("required", []))
        pad = "  " * (indent + 1)
        lines = ["{"]
        for k, v in props.items():
            doc = v.get("description")
            if doc:
                lines.append(f"{pad}/** {doc} */")
            lines.append(f"{pad}{k}{'' if k in req else '?'}: {ts_type(v, indent + 1)};")
        lines.append("  " * indent + "}")
        return "\n".join(lines)
    return "unknown"


def py_type(s: dict) -> str:
    if "enum" in s or "const" in s:
        vals = s.get("enum", [s.get("const")])
        return "Literal[" + ", ".join(json.dumps(v) if not isinstance(v, bool) else str(v) for v in vals) + "]"
    t = s.get("type")
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}.get(t) or (
        f"list[{py_type(s.get('items', {}))}]" if t == "array" else "dict[str, Any]")


def generate() -> tuple[str, str]:
    schemas = [json.loads(p.read_text()) for p in sorted(SCHEMAS.glob("*.schema.json"))]
    ts = [f"// {HEADER}", ""]
    py = [f'"""{HEADER}"""', "", "from __future__ import annotations", "",
          "from typing import Any, Literal, TypedDict", "", ""]
    for s in schemas:
        name = pascal(s["x-artifact-type"])
        ts.append(f"/** {s['title']} (schema {s['x-schema-version']}) */")
        ts.append(f"export interface {name} {ts_type(s)}")
        ts.append("")
        req = set(s.get("required", []))
        py.append(f"class {name}(TypedDict, total=False):")
        py.append(f'    """{s["title"]} (schema {s["x-schema-version"]}); required: {", ".join(sorted(req)) or "none"}."""')
        py.append("")
        for k, v in s["properties"].items():
            py.append(f"    {k}: {py_type(v)}")
        py += ["", ""]
    ts.append("export const SCHEMA_VERSIONS = " + json.dumps({s["x-artifact-type"]: s["x-schema-version"] for s in schemas},
                                                             indent=2) + " as const;")
    ts.append("")
    py.append("SCHEMA_VERSIONS = " + json.dumps({s["x-artifact-type"]: s["x-schema-version"] for s in schemas}, indent=4))
    py.append("")
    return "\n".join(ts), "\n".join(py)


def main() -> int:
    ts, py = generate()
    if "--check" in sys.argv:
        stale = [p for p, c in ((TS_OUT, ts), (PY_OUT, py)) if not p.exists() or p.read_text() != c]
        if stale:
            print("stale generated types:", *stale)
            return 1
        return 0
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(ts)
    PY_OUT.write_text(py)
    print("wrote", TS_OUT.relative_to(ROOT), PY_OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
